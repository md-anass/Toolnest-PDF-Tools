def test_end_to_end_normal_text_conversion():
    pdf_path = FIXTURES_DIR / "normal_text.pdf"
    with open(pdf_path, "rb") as f:
        upload_resp = client.post("/api/convert", files={"file": ("financial_report.pdf", f, "application/pdf")})
    assert upload_resp.status_code == 202
    upload_data = upload_resp.json()
    job_id = upload_data["job_id"]
    file_id = upload_data["file_id"]

    # Poll status until complete
    max_wait = 15
    start_time = time.time()
    completed = False
    status_data = {}

    while time.time() - start_time < max_wait:
        poll_resp = client.get(f"/api/convert/{job_id}")
        assert poll_resp.status_code == 200
        status_data = poll_resp.json()
        if status_data["status"] == "completed":
            completed = True
            break
        elif status_data["status"] == "failed":
            pytest.fail(f"Conversion failed: {status_data.get('error_message')}")
        time.sleep(0.5)

    assert completed, f"Job did not complete within {max_wait}s. Last status: {status_data}"
    assert status_data["progress"] == 100
    assert status_data["stage"] == "completed"

    res = status_data["result"]
    assert res is not None
    assert res["page_count"] == 1
    assert res["docx_filename"] == "financial_report.docx"
    assert res["extracted_elements"]["headings"] >= 1
    assert res["extracted_elements"]["paragraphs"] >= 1

    # Verify download
    download_resp = client.get(f"/api/download/{file_id}")
    assert download_resp.status_code == 200
    assert len(download_resp.content) > 1000

    # Verify that the generated bytes are a valid Word document
    import io
    docx_doc = Document(io.BytesIO(download_resp.content))
    doc_text = " ".join(p.text for p in docx_doc.paragraphs)
    assert "Quarterly Financial Analysis" in doc_text or "Executive Summary" in doc_text

    # Test file deletion & cleanup
    del_resp = client.delete(f"/api/files/{file_id}")
    assert del_resp.status_code == 200
    assert not get_upload_path(file_id).exists()
    assert not get_output_path(file_id).exists()


